import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sha256=createHash('sha256').update(html).digest('hex');
const version={artifactSha256:sha256,corpus:'BALOISE_HOME_2024-09',release:'foyer-workbench-v11'};
const source=`// Generated by scripts/build-worker.mjs; do not edit manually.\n`+
`const PAGE=${JSON.stringify(html)};\n`+
`const RELEASE=${JSON.stringify(version)};\n`+
`export default {fetch(request){const path=new URL(request.url).pathname;const method=request.method;`+
`if(method!=='GET'&&method!=='HEAD')return new Response('Method Not Allowed',{status:405,headers:{Allow:'GET, HEAD'}});`+
`if(path==='/__version')return new Response(method==='HEAD'?null:JSON.stringify(RELEASE),{headers:{'Content-Type':'application/json; charset=utf-8','Cache-Control':'no-store','X-Content-Type-Options':'nosniff'}});`+
`if(path!=='/'&&path!=='/index.html')return new Response('Not Found',{status:404});`+
`return new Response(method==='HEAD'?null:PAGE,{status:200,headers:{'Content-Type':'text/html; charset=utf-8','Cache-Control':'no-cache, max-age=0','X-Content-Type-Options':'nosniff','Referrer-Policy':'strict-origin-when-cross-origin','X-Frame-Options':'DENY','X-ClausePilot-Release':RELEASE.release,'X-ClausePilot-Artifact':RELEASE.artifactSha256}})}};\n`;
fs.mkdirSync(path.join(root,'dist'),{recursive:true});
fs.writeFileSync(path.join(root,'dist','worker.mjs'),source);
fs.writeFileSync(path.join(root,'dist','release.json'),JSON.stringify(version,null,2)+'\n');
console.log(JSON.stringify({artifactSha256:sha256,bytes:Buffer.byteLength(source)}));
